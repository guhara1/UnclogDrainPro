def _d(core, *seed):
    """스핀 → 채우기 → 80자 안에서 **가장 긴 꼬리**를 붙인다.
       ★자르지 않는다 — 잘린 문장이 검색 결과에 그대로 뜬다."""
    s = bank.fill(bank.spin(core, *seed), {}).strip()
    for t in TAILS:
        c = (s + ' ' + t).strip()
        if len(c) <= 80:
            return c
    return s[:79].rstrip(' ·,') + '.'


